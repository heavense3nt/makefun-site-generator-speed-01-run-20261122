/** The code units a backslash escapes: \ ` * _ [ ] ( ) # + - . ! > */
function isEscapableCode(c) {
  return (
    c === 92 || c === 96 || c === 42 || c === 95 || c === 91 || c === 93 || c === 40 || c === 41 || c === 35 || c === 43 || c === 45 || c === 46 || c === 33 || c === 62
  );
}

/** The first index from `from` where `s` holds `what` outside a backslash escape, or -1. */
function findUnescaped(s, what, from) {
  const wlen = what.length;
  for (let j = from; j <= s.length - wlen; j++) {
    if (s.charCodeAt(j) === 92 && j + 1 < s.length && isEscapableCode(s.charCodeAt(j + 1))) {
      j++;
      continue;
    }
    if (s.startsWith(what, j)) return j;
  }
  return -1;
}

/** The first single * from `from` (one whose run is not **), outside an escape, or -1. */
function findSingleStar(s, from) {
  for (let j = from; j < s.length; j++) {
    const c = s.charCodeAt(j);
    if (c === 92 && j + 1 < s.length && isEscapableCode(s.charCodeAt(j + 1))) {
      j++;
      continue;
    }
    if (c !== 42) continue;
    if (s.charCodeAt(j + 1) === 42) {
      j++;
      continue;
    }
    return j;
  }
  return -1;
}

const WS_TARGET = /\s/;

/**
 * `s` rendered inline, appended to `out`. Plain runs are flushed as slices
 * (escaped once each) instead of one escaped character at a time; nested
 * strong, emphasis and link text recurse into the same routine. The next
 * special character is found with native indexOf scans, so plain text is
 * never walked one character at a time in JavaScript.
 */
function inlineInto(s, env, out) {
  const n = s.length;
  let run = 0;
  let i = 0;
  while (i < n) {
    let j = n;
    let k = s.indexOf('\\', i);
    if (k !== -1 && k < j) j = k;
    k = s.indexOf('`', i);
    if (k !== -1 && k < j) j = k;
    k = s.indexOf('*', i);
    if (k !== -1 && k < j) j = k;
    k = s.indexOf('[', i);
    if (k !== -1 && k < j) j = k;
    if (j === n) break;
    i = j;
    const c = s.charCodeAt(i);
    if (c === 92) {
      if (i + 1 < n && isEscapableCode(s.charCodeAt(i + 1))) {
        if (i > run) out.push(escapeHtml(s.slice(run, i)));
        // Of the escapable characters only > needs HTML escaping.
        out.push(s.charCodeAt(i + 1) === 62 ? '&gt;' : s[i + 1]);
        i += 2;
        run = i;
      } else i++;
      continue;
    }
    if (c === 96) {
      const j2 = s.indexOf('`', i + 1);
      if (j2 > i + 1) {
        if (i > run) out.push(escapeHtml(s.slice(run, i)));
        out.push('<code>', escapeHtml(s.slice(i + 1, j2)), '</code>');
        i = j2 + 1;
        run = i;
      } else i++;
      continue;
    }
    if (c === 42) {
      if (s.charCodeAt(i + 1) === 42) {
        const j2 = findUnescaped(s, '**', i + 2);
        if (j2 > i + 2) {
          if (i > run) out.push(escapeHtml(s.slice(run, i)));
          out.push('<strong>');
          inlineInto(s.slice(i + 2, j2), env, out);
          out.push('</strong>');
          i = j2 + 2;
          run = i;
        } else i += 2;
        continue;
      }
      const j2 = findSingleStar(s, i + 1);
      if (j2 > i + 1) {
        if (i > run) out.push(escapeHtml(s.slice(run, i)));
        out.push('<em>');
        inlineInto(s.slice(i + 1, j2), env, out);
        out.push('</em>');
        i = j2 + 1;
        run = i;
      } else i++;
      continue;
    }
    // c === 91, '['
    const k2 = findUnescaped(s, ']', i + 1);
    const m = k2 !== -1 && s.charCodeAt(k2 + 1) === 40 ? s.indexOf(')', k2 + 2) : -1;
    const target = m === -1 ? '' : s.slice(k2 + 2, m);
    if (target !== '' && !WS_TARGET.test(target)) {
      if (i > run) out.push(escapeHtml(s.slice(run, i)));
      out.push('<a href="', escapeHtml(env.link(target)), '">');
      inlineInto(s.slice(i + 1, k2), env, out);
      out.push('</a>');
      i = m + 1;
      run = i;
      continue;
    }
    i++;
  }
  if (n > run) out.push(escapeHtml(s.slice(run, n)));
}

/** `s` rendered inline. */
function inline(s, env) {
  const out = [];
  inlineInto(s, env, out);
  return out.join('');
}

/** Whether `line` is blank (spaces and tabs only). */
function isBlank(line) {
  for (let i = 0; i < line.length; i++) {
    const c = line.charCodeAt(i);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

/** Whether `line` is only spaces or tabs from `from` on. */
function isSpacesToEnd(line, from) {
  for (let i = from; i < line.length; i++) {
    const c = line.charCodeAt(i);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

/**
 * A fence opening: a line of three backticks and an optional language
 * (A-Z, a-z, 0-9, _, +, -), then spaces or tabs only. Returns the language,
 * or null when the line is no fence opening.
 */
function fenceLang(line) {
  if (line.charCodeAt(0) !== 96 || line.charCodeAt(1) !== 96 || line.charCodeAt(2) !== 96) return null;
  let i = 3;
  while (i < line.length) {
    const c = line.charCodeAt(i);
    if (
      (c >= 65 && c <= 90) ||
      (c >= 97 && c <= 122) ||
      (c >= 48 && c <= 57) ||
      c === 95 ||
      c === 43 ||
      c === 45
    ) {
      i++;
    } else break;
  }
  return isSpacesToEnd(line, i) ? line.slice(3, i) : null;
}

/** Whether `line` closes a fence: three backticks, spaces or tabs after them. */
function isFenceClose(line) {
  return line.charCodeAt(0) === 96 && line.charCodeAt(1) === 96 && line.charCodeAt(2) === 96 && isSpacesToEnd(line, 3);
}

/**
 * A heading line's level and text, or null (a heading's text is never empty).
 * 1 to 6 #, at least one space or tab, then text (spaces and tabs at its end
 * dropped; closing #s are kept as text).
 */
function headingOf(line) {
  let depth = 0;
  while (depth < line.length && line.charCodeAt(depth) === 35) depth++;
  if (depth === 0 || depth > 6) return null;
  const c = line.charCodeAt(depth);
  if (c !== 32 && c !== 9) return null;
  let end = line.length;
  while (end > depth) {
    const d = line.charCodeAt(end - 1);
    if (d === 32 || d === 9) end--;
    else break;
  }
  const text = line.slice(depth, end);
  // The text is the run after the #s and their spaces/tabs, with trailing
  // spaces/tabs dropped; it must hold at least one non-space character.
  let start = depth;
  while (start < end) {
    const d = line.charCodeAt(start);
    if (d === 32 || d === 9) start++;
    else break;
  }
  if (start === end) return null;
  return { depth, text: line.slice(start, end) };
}

/** Whether `line` is a thematic break: --- or ***, then spaces or tabs only. */
function isHr(line) {
  if (line.length < 3) return false;
  const a = line.charCodeAt(0);
  const b = line.charCodeAt(1);
  const d = line.charCodeAt(2);
  if (!((a === 45 && b === 45 && d === 45) || (a === 42 && b === 42 && d === 42))) return false;
  return isSpacesToEnd(line, 3);
}

/** A paragraph line as it is rendered: spaces and tabs at either end dropped. */
function trimLine(line) {
  let s = 0;
  let e = line.length;
  while (s < e) {
    const c = line.charCodeAt(s);
    if (c === 32 || c === 9) s++;
    else break;
  }
  while (e > s) {
    const c = line.charCodeAt(e - 1);
    if (c === 32 || c === 9) e--;
    else break;
  }
  return line.slice(s, e);
}

/** Whether `line` ends a paragraph: blank, a fence, a heading or a break. */
function endsParagraph(line) {
  return isBlank(line) || fenceLang(line) !== null || headingOf(line) !== null || isHr(line);
}

/** A bullet item's text, or null. `- ` or `* ` then the item. */
function bulletOf(line) {
  const c = line.charCodeAt(0);
  if ((c === 45 || c === 42) && line.charCodeAt(1) === 32) return line.slice(2);
  return null;
}

/** An ordered item's number and text, or null. Digits and `. ` then the item. */
function orderedOf(line) {
  let i = 0;
  while (i < line.length && i < 9) {
    const c = line.charCodeAt(i);
    if (c >= 48 && c <= 57) i++;
    else break;
  }
  if (i === 0) return null;
  if (line.charCodeAt(i) !== 46 || line.charCodeAt(i + 1) !== 32) return null;
  return { start: Number(line.slice(0, i)), text: line.slice(i + 2) };
}

/** Whether `line` continues a list item: two or more spaces then a non-space. */
function isContinued(line) {
  if (line.charCodeAt(0) !== 32 || line.charCodeAt(1) !== 32) return false;
  let i = 2;
  while (i < line.length && line.charCodeAt(i) === 32) i++;
  return i < line.length && !isWS(line.charCodeAt(i));
}

/**
 * `src` rendered: its HTML (each block on its own lines, a "\n" after the
 * last), its table of contents (every level 2 and 3 heading: level, id and
 * its inline HTML) and its excerpt (the first paragraph's inline HTML, or "").
 * Lexing and rendering run in one pass over the lines, so no token objects
 * are built.
 */
function renderMarkdown(src, env) {
  const lines = src.split('\n');
  const ids = new Set();
  const blocks = [];
  const toc = [];
  let excerpt = null;
  let i = 0;
  const n = lines.length;
  while (i < n) {
    const line = lines[i];
    if (isBlank(line)) {
      i++;
      continue;
    }
    const lang = fenceLang(line);
    if (lang !== null) {
      const body = [];
      i++;
      while (i < n && !isFenceClose(lines[i])) body.push(lines[i++]);
      i++;
      let code = '<pre><code';
      if (lang !== '') code += ` class="language-${lang}"`;
      code += '>';
      for (const l of body) {
        code += escapeHtml(l);
        code += '\n';
      }
      code += '</code></pre>';
      blocks.push(code);
      continue;
    }
    const heading = headingOf(line);
    if (heading !== null) {
      const id = uniqueSlug(slugify(heading.text), ids);
      const html = inline(heading.text, env);
      blocks.push(`<h${heading.depth} id="${id}">${html}</h${heading.depth}>`);
      if (heading.depth === 2 || heading.depth === 3) toc.push({ level: heading.depth, id, html });
      i++;
      continue;
    }
    if (isHr(line)) {
      blocks.push('<hr>');
      i++;
      continue;
    }
    if (line.charCodeAt(0) === 62) {
      const body = [];
      while (i < n && lines[i].charCodeAt(0) === 62) {
        let l = lines[i++];
        l = l.charCodeAt(1) === 32 ? l.slice(2) : l.slice(1);
        body.push(trimLine(l));
      }
      const kept = body.filter((l) => l !== '');
      blocks.push(kept.length === 0 ? '<blockquote>\n</blockquote>' : `<blockquote>\n<p>${inline(kept.join('\n'), env)}</p>\n</blockquote>`);
      continue;
    }
    const bullet = bulletOf(line);
    const ordered = bullet === null ? orderedOf(line) : null;
    if (bullet !== null || ordered !== null) {
      const isOrdered = ordered !== null;
      const items = [];
      while (i < n) {
        if (isOrdered) {
          const m = orderedOf(lines[i]);
          if (m !== null) {
            items.push([trimLine(m.text)]);
            i++;
            continue;
          }
        } else {
          const m = bulletOf(lines[i]);
          if (m !== null) {
            items.push([trimLine(m)]);
            i++;
            continue;
          }
        }
        if (isContinued(lines[i])) {
          items[items.length - 1].push(trimLine(lines[i]));
          i++;
        } else break;
      }
      const tag = isOrdered ? 'ol' : 'ul';
      const open = isOrdered && ordered.start !== 1 ? `<ol start="${ordered.start}">` : `<${tag}>`;
      let out = `${open}\n`;
      for (const parts of items) out += `<li>${inline(parts.join('\n'), env)}</li>\n`;
      out += `</${tag}>`;
      blocks.push(out);
      continue;
    }
    const body = [trimLine(line)];
    i++;
    while (i < n && !endsParagraph(lines[i])) body.push(trimLine(lines[i++]));
    const text = body.join('\n');
    const html = inline(text, env);
    if (excerpt === null) excerpt = html;
    blocks.push(`<p>${html}</p>`);
  }
  let html = '';
  for (const b of blocks) {
    html += b;
    html += '\n';
  }
  return { html, toc, excerpt: excerpt ?? '' };
}

